Напиши короткую познавательную сказку (15–20 предложений) для ребёнка {{ $age }} лет.

Главный герой — {{ $gender }} по имени {{ $name }}.
Тема, которую нужно объяснить через сказку: {{ $request }}.

Жёсткие требования к сюжету и персонажам:
1. Поведение ВСЕХ персонажей должно быть логичным и объяснимым. Каждый поступок героя и второстепенных персонажей должен иметь понятную причину (любопытство, удивление, желание разобраться, реакцию на предыдущее событие). Нельзя, чтобы герой вдруг «просто понял» или «вдруг узнал». Понимание должно вырасти из конкретных событий и наблюдений в сказке.
2. Сюжет строится по чёткой цепочке:
- Сначала показываем, как герой сталкивается с вопросом или явлением в обычной ситуации и искренне недоумевает.
- Затем происходит событие, которое запускает маленькое сказочное приключение.
- В приключении герой шаг за шагом наблюдает, исследует и узнаёт, почему происходит именно так.
- Через свои действия, вопросы и открытия герой сам приходит к понятному объяснению.
- В конце герой радуется, что теперь понимает, и может объяснить это простыми словами.
3. Магические, сказочные или необычные элементы (если они появляются) должны быть органично вплетены в историю и помогать герою лучше увидеть и понять тему. Они не должны появляться «из ниоткуда» без причины.
4. Объяснение должно быть простым, образным и доступным для возраста ребёнка. Нельзя давать сухие научные формулировки — только через живые события и образы сказки.
5. Сказка должна ощущаться как маленькое интересное приключение-открытие, а не как урок или нравоучение.

