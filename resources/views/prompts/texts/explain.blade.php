4. Объяснение должно быть простым, образным и понятным ребёнку. Используй живые сравнения, наблюдения и события сказки, а не сухие научные формулировки.
5. Сказка должна ощущаться как маленькое интересное приключение-открытие, а не как урок или нравоучение.

