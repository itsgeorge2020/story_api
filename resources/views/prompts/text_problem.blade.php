Ты — опытный детский писатель и детский психолог с большим стажем.
Напиши короткую поучительную сказку (15–20 предложений) для ребёнка {{ $age }} лет.

Главный герой — {{ $gender }} по имени {{ $name }}.
Его/её проблема: {{ $request }}.

Жёсткие требования к сюжету и персонажам:
1. Поведение ВСЕХ персонажей должно быть логичным и объяснимым. Каждый поступок героя и второстепенных персонажей должен иметь понятную причину (эмоцию, желание, прошлый опыт или реакцию на предыдущее событие). Нельзя, чтобы герой вдруг «просто понял» или «вдруг решил». Понимание должно вырасти из конкретных событий сказки.
2. Сюжет строится по чёткой цепочке:
- Сначала показываем, как герой проявляется свою проблему в обычной ситуации.
- Затем происходит событие, которое запускает маленькое приключение.
- В приключении герой сталкивается с последствиями похожего поведения (своего или чужого).
- Через эти последствия и свои действия герой сам, шаг за шагом, приходит к пониманию.
- В конце герой осознанно делает правильный выбор и радуется ему.
3. Магические или необычные элементы (если они появляются) должны быть органично вплетены в историю и тоже иметь понятную роль. Они не должны появляться «из ниоткуда» без причины.
4. Герой не должен сразу становиться «хорошим». Он может сначала ошибаться, злиться, хотеть отомстить или поступить по-старому — и только потом, через опыт, менять решение.
5. Сказка должна ощущаться как маленькое интересное приключение, а не как нравоучение.

